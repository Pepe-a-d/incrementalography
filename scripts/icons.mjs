// Copies the Tabler icons the game uses (outline set, MIT license) into src/icons.js, so the game ships only those.
// Run after changing the list: node scripts/icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = `feather droplet droplet-plus droplet-half droplets bottle brush text-size ruler-2 coin coins italic book alphabet-latin
hourglass hourglass-high clock-plus shield shield-check wind leaf target bolt trending-up eraser flame chart-arrows-vertical rocket link
user-plus users run arrows-horizontal award gauge medal sun sparkles candle writing bookmark sun-high book-2 crown
bell arrows-maximize corner-down-left copy keyboard notes file-text bug cpu zoom-in code database braces device-desktop
eye eyeglass telescope atom quote brain planet pencil trophy stars laurel-wreath gift heart clipboard-text
star settings focus-centered book-upload file-plus lock binary-tree-2 building
moon music typography hand-finger exclamation-mark coffee bandage wave-sine antenna-bars-5 bell-ringing terminal-2 clock`.split(/\s+/).filter(Boolean);

const dir = 'node_modules/@tabler/icons/icons/outline';
const out = {};
for (const n of NAMES) {
  const svg = readFileSync(`${dir}/${n}.svg`, 'utf8');
  // keep the drawing, drop the svg wrapper and Tabler's invisible 24×24 frame
  out[n] = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b[^>]*\/>/g)]
    .map((m) => m[0].replace(/\s+/g, ' '))
    .filter((t) => !t.includes('stroke="none"'))
    .join('');
}
const lic = readFileSync('node_modules/@tabler/icons/LICENSE', 'utf8').trim().split('\n').map((l) => `// ${l}`.trimEnd()).join('\n');
writeFileSync('src/icons.js', `// Icons: Tabler Icons (outline), https://tabler.io/icons — generated by scripts/icons.mjs, don't edit by hand.
${lic}

export const ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, ',\n}')};

/** An icon as inline SVG (24×24, drawn with the current text colour). */
export const icon = (name, cls = 'ic') => \`<svg class="\${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${ICONS[name] || ''}</svg>\`;
`);
console.log(`${NAMES.length} icons → src/icons.js`);
